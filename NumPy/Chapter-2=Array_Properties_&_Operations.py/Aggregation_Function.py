'''

np.sum(arrar_name) --> for adding all elements
np.mean(arrar_name) --> for getting mean
np.max(arrar_name) --> for the maximum value among all elements
np.min(arrar_name) --> for mimimum value among all elements
np.std(arrar_name) --> for standard deviation
np.var(arrar_name) --> for variance

'''

import numpy as np
arr = np.array([10,30,20,40,50])

print(np.sum(arr))
print(np.min(arr))
print(np.max(arr))
print(np.std(arr))
print(np.var(arr))
print(np.mean(arr))