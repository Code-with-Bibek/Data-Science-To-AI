'''
print even numbers from 1 to 100 using for

'''
for i in range(100):
    if(i % 2 == 0):
        print(i)

# or

for i in range(2,100,2):
    if(i % 2 == 0):
        print(i)



'''
print odd numbers from 1 to 100 using for

'''
for i in range(100):
    if(i % 2 != 0):
        print(i)

#or 

for i in range(1,100,2):
    if(i % 2 != 0):
        print(i)

    